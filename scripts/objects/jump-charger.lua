-- JUMP CHARGER RUNTIME ---------------------------------------------------------
--
-- Jump Charger used to be a separate world entity with its own runtime object.
-- It is now battery-equipment inside the Mobile Factory equipment grid.
--
-- There is intentionally no JC object anymore. Factorio handles the Charger's
-- normal electrical charging; JD:scanEquipment() reads the installed equipment
-- directly and consumes its stored energy when a jump completes.
--
-- This file remains as a compatibility require because control.lua still loads
-- the historical module path. Keeping the module empty is safer than keeping
-- a dead runtime object which could accidentally register nonexistent entities.
